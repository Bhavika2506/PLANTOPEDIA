    fun getCropById(cropId: String): CropLibraryItem? {
        return crops.find { it.id.equals(cropId, ignoreCase = true) }
    }

    fun getDiseasesForCrop(cropId: String): List<DiseasePestItem> {
        val specific = diseasesAndPests.filter { it.cropId.equals(cropId, ignoreCase = true) }
        return if (specific.isNotEmpty()) specific else diseasesAndPests.filter { it.cropId.equals("Tomato", ignoreCase = true) }
    }

    fun getDiseaseById(diseaseId: String): DiseasePestItem? {
        return diseasesAndPests.find { it.id.equals(diseaseId, ignoreCase = true) }
    }

    fun getTipsForCrop(cropId: String): List<CultivationTipItem> {
        val specific = cultivationTips.filter { it.cropId.equals(cropId, ignoreCase = true) }
        val general = cultivationTips.filter { it.cropId.equals("General", ignoreCase = true) }
        return if (specific.isNotEmpty()) specific + general else cultivationTips.filter { it.cropId.equals("Tomato", ignoreCase = true) } + general
    }

    fun getTipById(tipId: String): CultivationTipItem? {
        return cultivationTips.find { it.id.equals(tipId, ignoreCase = true) }
    }
